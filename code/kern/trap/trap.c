//lab3 dependency adapted for Lab5 2412933
static void interrupt_handler(struct trapframe *tf)
{
    uintptr_t cause = tf->cause & ~((uintptr_t)1 << 63);
    switch (cause) {
    case IRQ_S_TIMER:
        clock_set_next_event();
        ticks++;
        /* Lab5 spin/waitkill need a running user loop to relinquish the CPU.
         * trap() performs the switch only on the return-to-user boundary.
         */
        if (current != NULL) {
            current->need_resched = 1;
        }
        if (ticks % TICK_NUM == 0) {
            print_ticks();
        }
        break;
    case IRQ_S_SOFT:
        clear_csr(sip, MIP_SSIP);
        break;
    default:
        print_trapframe(tf);
        break;
    }
}

//lab5 function1 2412933 update exception_handler
/* Global linkage is required by tools/test_lab5.c's injected syscall test. */
void exception_handler(struct trapframe *tf)
{
    switch (tf->cause) {
    case CAUSE_USER_ECALL:
        /* ECALL is a 32-bit instruction, independent of compressed support. */
        tf->epc += 4;
        syscall();
        return;
    case CAUSE_STORE_PAGE_FAULT:
        if (current != NULL && current->mm != NULL) {
            int result = cow_resolve_write(current->mm, tf->tval);
            if (result == 0) {
                /* Retry the same store, including a legitimate kernel copy. */
                return;
            }
            if (result == -E_NO_MEM) {
                do_exit(-E_NO_MEM);
                panic("do_exit returned after a COW allocation failure");
            }
        }
        break;
    default:
        break;
    }
    print_trapframe(tf);
    if (!trap_in_kernel(tf) && current != NULL) {
        do_exit(-E_KILLED);
        panic("do_exit returned after a fatal user exception");
    }
    /* Boot uses the explicit __trapret path. No implicit EBREAK-as-exec ABI. */
    panic("unhandled kernel exception");
}


static inline void trap_dispatch(struct trapframe *tf)
{
    if ((intptr_t)tf->cause < 0)
    {
        // interrupts
        interrupt_handler(tf);
    }
    else
    {
        // exceptions
        exception_handler(tf);
    }
}

/* *
 * trap - handles or dispatches an exception/interrupt. if and when trap() returns,
 * the code in kern/trap/trapentry.S restores the old CPU state saved in the
 * trapframe and then uses the iret instruction to return from the exception.
 * */
void trap(struct trapframe *tf)
{
    // dispatch based on what type of trap occurred
    //    cputs("some trap");
    if (current == NULL)
    {
        trap_dispatch(tf);
    }
    else
    {
        struct trapframe *otf = current->tf;
        current->tf = tf;

        bool in_kernel = trap_in_kernel(tf);

        trap_dispatch(tf);

        current->tf = otf;
        if (!in_kernel)
        {
            if (current->flags & PF_EXITING)
            {
                do_exit(-E_KILLED);
            }
            if (current->need_resched)
            {
                schedule();
            }
        }
    }
}
